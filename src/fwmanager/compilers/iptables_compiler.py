"""Compiler translating declarative firewall policies to legacy iptables commands."""

from typing import List

from fwmanager.models.rules import FirewallPolicy, FirewallRule


class IptablesCompiler:
    """Compiles FirewallPolicy objects into sequential iptables CLI invocations."""

    @staticmethod
    def compile_rule(rule: FirewallRule) -> str:
        """Compile a single FirewallRule into an iptables argument vector."""
        args: List[str] = ["iptables", "-A", rule.chain]

        # Interfaces
        if rule.interface_in:
            args.extend(["-i", rule.interface_in])
        if rule.interface_out:
            args.extend(["-o", rule.interface_out])

        # IPs
        if rule.source_ip:
            args.extend(["-s", rule.source_ip])
        if rule.destination_ip:
            args.extend(["-d", rule.destination_ip])

        # State tracking
        if rule.state:
            states_str = ",".join(s.upper() for s in rule.state)
            args.extend(["-m", "conntrack", "--ctstate", states_str])

        # Protocol & Port
        if rule.protocol != "all":
            args.extend(["-p", rule.protocol])
            if rule.port:
                args.extend(["--dport", rule.port])

        # Action
        args.extend(["-j", rule.action])

        # Comment
        if rule.comment:
            args.extend(["-m", "comment", "--comment", f'"{rule.comment}"'])

        return " ".join(args)

    def compile_policy(self, policy: FirewallPolicy) -> List[str]:
        """Compile entire policy into a list of sequential iptables shell commands."""
        commands: List[str] = [
            f"# Generated by Linux Firewall Manager - Policy: {policy.name}",
            "iptables -F",  # Flush current rules
            "iptables -X",  # Delete user-defined chains
        ]

        # Set default policies
        for cd in policy.chain_defaults:
            commands.append(f"iptables -P {cd.chain} {cd.default_action}")

        # Add rules
        for r in policy.rules:
            commands.append(self.compile_rule(r))

        return commands
