"""Compiler translating declarative firewall policies to native nftables rulesets."""

from typing import List

from fwmanager.models.rules import FirewallPolicy, FirewallRule


class NftablesCompiler:
    """Compiles FirewallPolicy objects into valid nftables syntax."""

    @staticmethod
    def compile_rule(rule: FirewallRule) -> str:
        """Compile a single FirewallRule into an nftables statement."""
        parts: List[str] = []

        # Interface
        if rule.interface_in:
            parts.append(f"iifname {rule.interface_in}")
        if rule.interface_out:
            parts.append(f"oifname {rule.interface_out}")

        # IP addresses
        if rule.source_ip:
            parts.append(f"ip saddr {rule.source_ip}")
        if rule.destination_ip:
            parts.append(f"ip daddr {rule.destination_ip}")

        # Connection state
        if rule.state:
            states_str = ",".join(s.lower() for s in rule.state)
            parts.append(f"ct state {{ {states_str} }}")

        # Protocol & Port
        if rule.protocol != "all":
            parts.append(rule.protocol)
            if rule.port:
                if ":" in rule.port:
                    parts.append(f"dport {rule.port.replace(':', '-')}")
                else:
                    parts.append(f"dport {rule.port}")

        # Action
        act_lower = rule.action.lower()
        if act_lower == "log":
            prefix = rule.comment or f"FW-LOG-{rule.id}"
            parts.append(f'log prefix "{prefix}: "')
        else:
            parts.append(act_lower)

        # Comment
        if rule.comment:
            parts.append(f'comment "{rule.comment}"')

        return " ".join(parts)

    def compile_policy(
        self, policy: FirewallPolicy, table_family: str = "inet", table_name: str = "filter"
    ) -> str:
        """Compile an entire FirewallPolicy into an nftables configuration file."""
        lines: List[str] = [
            f"# Generated by Linux Firewall Manager - Policy: {policy.name}",
            f"table {table_family} {table_name} {{",
        ]

        # Group rules by chain
        chains = ["INPUT", "FORWARD", "OUTPUT"]
        defaults = {cd.chain: cd.default_action.lower() for cd in policy.chain_defaults}

        for chain in chains:
            hook = chain.lower()
            default_act = defaults.get(chain, "drop")
            lines.append(f"    chain {chain} {{")
            lines.append(f"        type filter hook {hook} priority 0; policy {default_act};")

            chain_rules = [r for r in policy.rules if r.chain.upper() == chain]
            for r in chain_rules:
                compiled = self.compile_rule(r)
                lines.append(f"        {compiled}")

            lines.append("    }")

        lines.append("}")
        return "\n".join(lines)
